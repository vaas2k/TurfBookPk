import { Router } from 'express';
import { AdminController } from '../controllers/adminController.js';
import { requireAdmin, requireAuth } from '../middleware/auth.js';
import { TokenService } from '../services/tokenService.js';

export function createAdminRouter(controller: AdminController, tokenService: TokenService): Router {
  const router = Router();
  router.use(requireAuth(tokenService), requireAdmin());
  router.get('/dashboard', controller.dashboard);
  router.get('/attention-counts', controller.attentionCounts);
  router.get('/platform-finance', controller.platformFinance);
  router.post('/financial-proof-upload', controller.financialProofUpload);
  router.get('/vendors', controller.listVendors);
  router.get('/vendors/:id/verification', controller.vendorVerification);
  router.get('/vendors/:id', controller.vendorDetail);
  router.get('/vendors/:id/financial-activity', controller.vendorFinancialActivity);
  router.patch('/vendors/:id/verification/:area', controller.reviewVendorVerification);
  router.post('/vendors/:id/approve', controller.approveVendor);
  router.get('/verification-documents/:id/download', controller.vendorDocumentDownload);
  router.get('/grounds', controller.listGrounds);
  router.get('/grounds/:id/verification', controller.groundVerification);
  router.patch('/grounds/:id/verification/review', controller.reviewGroundVerification);
  router.post('/grounds/:id/approve', controller.approveGround);
  router.get('/ground-verification-documents/:id/download', controller.groundDocumentDownload);
  router.get('/grounds/:id', controller.groundDetail);
  router.get('/users', controller.listUsers);
  router.get('/audit-logs', controller.auditLogs);
  router.get('/transactions', controller.listTransactions);
  router.get('/operations', controller.operations);
  router.get('/operations/push-outbox/dead', controller.deadPushes);
  router.post('/operations/push-outbox/:id/retry', controller.retryDeadPush);
  router.get('/refunds', controller.listRefunds);
  router.get('/refund-cases', controller.refundCases);
  router.post('/refund-cases/:id/approve', controller.approveRefund);
  router.post('/refund-cases/:id/complete', controller.completeRefund);
  router.post('/refund-cases/:id/fail', controller.failRefund);
  router.get('/financial-disputes', controller.listFinancialDisputes);
  router.post('/financial-disputes', controller.createFinancialDispute);
  router.post('/financial-disputes/:id/resolve', controller.resolveFinancialDispute);
  router.get('/vendor-balances', controller.vendorBalances);
  router.get('/vendor-balances/:id/entries', controller.vendorPayableEntries);
  router.post('/vendor-balances/:id/payouts', controller.createPayout);
  router.get('/payouts', controller.listPayouts);
  router.post('/payouts/:id/complete', controller.completePayout);
  router.post('/payouts/:id/fail', controller.failPayout);
  router.patch('/grounds/:id/activation', controller.setGroundActivation);
  router.get('/review-reports', controller.listReports);
  router.patch('/review-reports/:id', controller.resolveReport);
  router.patch('/users/:id/suspension', controller.setUserSuspension);
  return router;
}
